export function translate(lang: Lang, key: string, variables?: Record<string, string | number>): string {
  const entry = dictionary[key]
  let value = entry ? entry[lang] : key
  if (variables) {
    for (const [name, replacement] of Object.entries(variables)) {
      value = value.replaceAll(`{{${name}}}`, String(replacement))
    }
  }
  return value
}

export function translateValue(lang: Lang, value: unknown): string {
  if (value == null || value === '') return '—'
  const text = String(value)
  if (lang === 'fr') return text
  return valueTranslations[text] ?? text
}

export function translateError(lang: Lang, error: unknown, fallbackKey: string): string {
  const message = error instanceof Error ? error.message : ''
  const http = /^Erreur (\d+)$/.exec(message)
  if (http) return translate(lang, 'api.httpError', { status: http[1] })
  if (message && dictionary[message]) return translate(lang, message)
  if (message) return message
  return translate(lang, fallbackKey)
}
